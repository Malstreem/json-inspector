import fs from 'node:fs';
import { execSync } from 'node:child_process';

execSync('npx asc assembly/spatial.ts --target release', { stdio: 'inherit' });

const bytes = fs.readFileSync('public/spatial.wasm');
const base64 = bytes.toString('base64');
const tsContent = `// Auto-generated by scripts/build-wasm.mjs - DO NOT EDIT MANUALLY
export const SPATIAL_WASM_BASE64 = '${base64}';
`;
fs.writeFileSync('src/graph/wasm-spatial-binary.ts', tsContent, 'utf8');
console.log(`Wasm built: public/spatial.wasm (${bytes.byteLength} bytes)`);
